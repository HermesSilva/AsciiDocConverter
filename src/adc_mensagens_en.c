const char* adc_msgs_tr(const ADC_Mensagens* pM, const char* pFrasePT) {
    if (!pFrasePT || !pM || pM->idioma != ADC_IDIOMA_EN) return pFrasePT;
    for (size_t i = 0; i < sizeof TABELA / sizeof TABELA[0]; i++)
        if (TABELA[i].pt == pFrasePT || strcmp(TABELA[i].pt, pFrasePT) == 0) return TABELA[i].en;
    return pFrasePT;
}
